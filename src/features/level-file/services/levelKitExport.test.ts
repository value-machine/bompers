import { readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { CONTENT_CATALOG } from "@/features/content-catalog/api/contentCatalogApi";
import {
  buildKitCatalog,
  planLevelKitSync,
  replaceGeneratedBlock,
} from "@/features/level-file/services/levelKitExport";

const readRepoFile = (rel: string): string => {
  try {
    return readFileSync(path.join(process.cwd(), rel), "utf8");
  } catch {
    return "";
  }
};

describe("levelKitExport", () => {
  it("should list every catalog ID of every kind when the kit catalog is built", () => {
    const kit = buildKitCatalog();
    for (const [kind, entries] of Object.entries(CONTENT_CATALOG)) {
      const ids = (kit[kind] as { id: string }[]).map((e) => e.id);
      expect(ids).toEqual(Object.keys(entries));
    }
  });

  it("should match the committed kit files when the catalog in code is unchanged (drift check)", () => {
    const stale = planLevelKitSync(readRepoFile).filter((f) => f.current !== f.expected);
    expect(stale.map((f) => f.path)).toEqual([]);
  });

  it("should flag a file as stale when its generated block lags behind", () => {
    const plan = planLevelKitSync((p) =>
      p.endsWith("AUTHORING.md") ? readRepoFile(p).replace("`dirt`", "`mud`") : readRepoFile(p)
    );
    expect(plan.filter((f) => f.current !== f.expected).map((f) => f.path)).toEqual([
      "public/level-kit/v1/AUTHORING.md",
    ]);
  });

  it("should replace only the text between the markers", () => {
    const start = "<!-- level-kit:x:start (generated by pnpm level-kit:sync; do not edit) -->";
    const text = `before\n${start}\nold\n<!-- level-kit:x:end -->\nafter`;
    expect(replaceGeneratedBlock(text, "x", "new")).toBe(
      `before\n${start}\nnew\n<!-- level-kit:x:end -->\nafter`
    );
  });

  it("should throw when a file has lost its markers", () => {
    expect(() => replaceGeneratedBlock("no markers", "x", "new")).toThrow(
      /Missing generated-block/
    );
  });
});
