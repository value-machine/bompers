import {
  CATALOG_DEFAULTS,
  LEVEL_FORMAT_VERSION,
  exportCatalog,
  type CatalogEntryByKind,
  type ContentKind,
} from "@/features/content-catalog/api/contentCatalogApi";
import { exportObjectCatalog } from "@/features/level-objects/api/levelObjectsApi";
import { buildLevelPrompt } from "@/features/level-kit/services/levelPrompt";
import { terrainSwatch, toCssColor } from "@/shared/config/gamePalette";

/**
 * The public level kit's generated parts, built from the content catalog and level defaults in
 * code (the single source). `scripts/sync-level-kit.mjs` writes them (`pnpm level-kit:sync`)
 * and fails CI when the files lag behind (`pnpm level-kit:check`). Pure: no file access here.
 */
const KIT_DIR = `public/level-kit/v${LEVEL_FORMAT_VERSION}`;
const KINDS: readonly ContentKind[] = ["material", "color", "effect", "sound", "behavior", "item"];
const CATALOG_IDS_BLOCK = "catalog-ids";

/**
 * The kit's catalog.json: `exportCatalog()` (format version, defaults, IDs per kind), with each
 * colour's RGB from the game palette so the preview paints terrain the way the game does.
 */
export function buildKitCatalog(): Record<string, unknown> {
  const catalog = exportCatalog();
  return {
    $comment:
      "GENERATED from the content catalog in the game code by `pnpm level-kit:sync`. Do not edit. Spec: documentation/game/LEVEL_FORMAT.md.",
    ...catalog,
    color: catalog.color.map((entry) => {
      const swatch = terrainSwatch(entry.id);
      return { ...entry, fill: toCssColor(swatch.fill), lip: toCssColor(swatch.lip) };
    }),
    // Placed objects (level-objects D5): kinds, variants and size ranges from the object registry.
    object: exportObjectCatalog(),
  };
}

const roleDefaults = (kind: ContentKind, id: string): string[] => {
  if (kind === "material") return CATALOG_DEFAULTS.material === id ? ["default for terrain"] : [];
  if (kind === "color") {
    const materials = exportCatalog().material.filter((m) => m.defaultColor === id);
    return materials.map((m) => `default for ${m.id}`);
  }
  if (kind !== "item") return [];
  return Object.entries(CATALOG_DEFAULTS.items)
    .filter(([, v]) => [v].flat().includes(id))
    .map(([role]) => `default for ${role}`);
};

const SURFACE_NOTES = {
  plain: "smooth slab",
  ice: "gloss streaks + white rim",
} as const;

function entryNotes<K extends ContentKind>(kind: K, entry: CatalogEntryByKind[K]): string {
  const facts: string[] = [];
  if ("toughness" in entry) {
    facts.push(entry.toughness === null ? "unbreakable" : `toughness ${entry.toughness}`);
    if (entry.friction < 1) facts.push("slippery");
    facts.push(`looks: ${SURFACE_NOTES[entry.surface]}`);
  }
  if ("effect" in entry) facts.push(`effect \`${entry.effect}\`, sound \`${entry.sound}\``);
  if ("use" in entry) facts.push(`use: ${entry.use}`);
  return [...facts, ...roleDefaults(kind, entry.id)].join(", ");
}

/** Markdown table of every catalog ID, for AUTHORING.md and LEVEL_FORMAT.md. */
export function renderCatalogIdTable(): string {
  const entries = exportCatalog();
  const rows = KINDS.flatMap((kind) => {
    const list = entries[kind] as CatalogEntryByKind[typeof kind][];
    if (list.length === 0) return [`| ${kind} | — | none yet; leave it out | |`];
    return list.map(
      (entry) => `| ${kind} | \`${entry.id}\` | ${entry.label} | ${entryNotes(kind, entry)} |`
    );
  });
  const objectRows = exportObjectCatalog().flatMap((recipe) =>
    recipe.variants.map(
      (v) =>
        `| object | \`${recipe.kind}\` / \`${v.id}\` | ${v.label} | height ${recipe.height.min}–${recipe.height.max}, width ${v.aspect.min}–${v.aspect.max} × height${v.id === recipe.defaultVariant ? ", default variant" : ""} |`
    )
  );
  return ["| Kind | ID | Label | Notes |", "|---|---|---|---|", ...rows, ...objectRows].join("\n");
}

const markers = (block: string) => ({
  start: `<!-- level-kit:${block}:start (generated by pnpm level-kit:sync; do not edit) -->`,
  end: `<!-- level-kit:${block}:end -->`,
});

/** Replaces the text between a block's marker comments; throws when the markers are missing. */
export function replaceGeneratedBlock(text: string, block: string, content: string): string {
  const { start, end } = markers(block);
  const from = text.indexOf(start);
  const to = text.indexOf(end);
  if (from < 0 || to < from)
    throw new Error(`Missing generated-block markers "${start}" … "${end}".`);
  return `${text.slice(0, from + start.length)}\n${content}\n${text.slice(to)}`;
}

export interface KitFile {
  /** Repository-relative path. */
  path: string;
  /** Expected content, given the file's current content. */
  render: (current: string) => string;
}

const withCatalogTable = (current: string): string =>
  replaceGeneratedBlock(current, CATALOG_IDS_BLOCK, renderCatalogIdTable());

export const LEVEL_KIT_FILES: readonly KitFile[] = [
  {
    path: `${KIT_DIR}/catalog.json`,
    render: () => `${JSON.stringify(buildKitCatalog(), null, 2)}\n`,
  },
  { path: `${KIT_DIR}/AUTHORING.md`, render: withCatalogTable },
  // The copyable AI prompt, whole file (level-gen-prompt D2): the app copies the same text.
  { path: `${KIT_DIR}/LEVEL_PROMPT.md`, render: () => buildLevelPrompt() },
  { path: "documentation/game/LEVEL_FORMAT.md", render: withCatalogTable },
];

export interface KitFileState {
  path: string;
  current: string;
  expected: string;
}

/** Every kit file with its current and expected content (`read` returns "" for a missing file). */
export const planLevelKitSync = (read: (path: string) => string): KitFileState[] =>
  LEVEL_KIT_FILES.map((file) => {
    const current = read(file.path);
    return { path: file.path, current, expected: file.render(current) };
  });
